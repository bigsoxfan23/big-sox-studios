// Embed only these exact assets so no platform static-asset bypass is possible.
import { readFileSync, writeFileSync } from 'node:fs';
const assets = {};
for (const [path, file, type] of [
 ['/', 'index.html', 'text/html; charset=utf-8'],
 ['/app.js', 'app.js', 'text/javascript; charset=utf-8'],
 ['/styles.css', 'styles.css', 'text/css; charset=utf-8']
]) assets[path] = { type, body: readFileSync(new URL(`../public/${file}`, import.meta.url), 'utf8') };
const output = `// Generated by scripts/bundle-ui.mjs; do not edit.\nexport const assets = ${JSON.stringify(assets, null, 1)};\n`;
const target = new URL('../src/ui-assets.mjs', import.meta.url);
if (process.argv.includes('--check')) {
 if (readFileSync(target, 'utf8') !== output) throw new Error('UI bundle stale; run npm run bundle-ui');
} else writeFileSync(target, output);
